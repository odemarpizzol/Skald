// Builds Skald/QuestZones.lua: for each QuestDB flavour (Vanilla, TBC, Forever) the quests of every map, with the
// race and class masks, so the Index card reads a few hundred numbers instead of walking every quest of QuestDB
// (measured: 648 ms in the game the first time the Index was opened).
// Run: node dev/tools/gen_quest_zones.js [path to the QuestDB addon folder]
// The rules are the ones ZoneCard.lua applied to the live data: a quest placed in a zone with a map, not hidden,
// not repeatable (special flags 1 and 2); the race and class are filtered when the card is drawn.
const { lua, lauxlib, lualib, to_luastring, to_jsstring } = require('fengari');
const fs = require('fs');
const path = require('path');

const QDB = process.argv[2] || '/mnt/d/Games/World of Warcraft/_anniversary_/Interface/AddOns/QuestDB';
const OUT = path.resolve(__dirname, '../../QuestZones.lua');
const FLAVOURS = ['Vanilla', 'TBC', 'Forever'];

function run(L, file, name) {
  const code = fs.readFileSync(file);
  if (lauxlib.luaL_loadbuffer(L, code, code.length, to_luastring('@' + name)) !== 0 || lua.lua_pcall(L, 0, 0, 0) !== 0)
    throw new Error(name + ': ' + to_jsstring(lua.lua_tolstring(L, -1)));
}

const DRIVER = `
local lib = LibStub("LibQuestDB-1.0")
local maps = {}
local n = 0
for _, id in ipairs(lib:GetQuestIds()) do
  local q = lib:GetQuest(id)
  local zone = q and q.zoneOrSort
  if type(zone) == "number" and zone > 0 and not q.hidden then
    local special = q.specialFlags or 0
    local repeatable = special % 2 == 1 or math.floor(special / 2) % 2 == 1
    if not repeatable then
      local map = lib:GetUiMapId(zone)
      if map then
        maps[map] = maps[map] or {}
        table.insert(maps[map], id .. ":" .. (q.requiredRaces or 0) .. ":" .. (q.requiredClasses or 0))
        n = n + 1
      end
    end
  end
end
local keys = {}
for m in pairs(maps) do keys[#keys + 1] = m end
table.sort(keys)
local out = {}
for _, m in ipairs(keys) do out[#out + 1] = string.format("[%d]=%q,", m, table.concat(maps[m], " ")) end
return table.concat(out, "\\n"), n, #keys
`;

let body = '';
const stats = [];
for (const f of FLAVOURS) {
  const L = lauxlib.luaL_newstate();
  lualib.luaL_openlibs(L);
  run(L, path.join(QDB, 'libs/LibStub/LibStub.lua'), 'LibStub');
  run(L, path.join(QDB, 'LibQuestDB-1.0.lua'), 'LibQuestDB');
  run(L, path.join(QDB, 'Data', f, '_core/Quests.lua'), f + '/Quests');
  run(L, path.join(QDB, 'Data', f, '_core/Zones.lua'), f + '/Zones');
  if (lauxlib.luaL_loadbuffer(L, to_luastring(DRIVER), null, to_luastring('driver')) !== 0 || lua.lua_pcall(L, 0, 3, 0) !== 0)
    throw new Error(f + ': ' + to_jsstring(lua.lua_tolstring(L, -1)));
  const text = to_jsstring(lua.lua_tolstring(L, -3));
  stats.push(f + ': ' + lua.lua_tonumber(L, -2) + ' quests on ' + lua.lua_tonumber(L, -1) + ' maps');
  body += `Z.${f} = {\n${text}\n}\n`;
}

const head = `-- Generated by dev/tools/gen_quest_zones.js from the QuestDB addon. Do not edit by hand.
--
-- Derived from LibQuestDB / QuestDB, Copyright (c) 2026 Pimptasty, MIT License
-- (https://www.curseforge.com/wow/addons/questdb), whose quest data is itself derived from the CMaNGOS world
-- databases (classic-db and tbc-db, GPL-3.0; facts extracted and re-expressed, no CMaNGOS file is redistributed)
-- and, for WoW Forever's own quests, from TOGTools. Permission is granted to use, copy, modify, merge and
-- distribute this derived data under the terms of the MIT License of QuestDB, whose copyright notice above is kept.
--
-- For each flavour of QuestDB and each map: the quests placed in a zone of the map that are neither hidden nor
-- repeatable, as "id:requiredRaces:requiredClasses" separated by spaces. ZoneCard.lua reads the map shown and
-- filters by race and class: no walk over every quest in the game.
local _, ns = ...
local Z = {}
ns.QuestZones = Z
`;
fs.writeFileSync(OUT, head + body);
console.log(stats.join('\n'));
console.log('written ' + OUT + ' (' + Math.round(fs.statSync(OUT).size / 1024) + ' KB)');
